def parse_fields(spec: str) -> tuple[FieldSpec, ...]:
    fields: list[FieldSpec] = []
    for token in spec.split():
        name, type_name = token.split(":", 1)
        required = not name.startswith("?")
        if not required:
            name = name[1:]
        fields.append(FieldSpec(name=name, type_name=type_name, required=required))
    return tuple(fields)


def contract_rows() -> tuple[tuple[FamilySpec, str, tuple[FieldSpec, ...]], ...]:
    rows: list[tuple[FamilySpec, str, tuple[FieldSpec, ...]]] = []
    for family in FAMILIES:
        for name, field_string, _ in family.rows:
            rows.append((family, name, parse_fields(field_string)))
    return tuple(rows)
