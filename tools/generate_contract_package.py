def outputs() -> dict[Path, str]:
    valid_fixtures = {name: fixture_for(name) for name in CONTRACTS}
    invalid = invalid_fixtures(valid_fixtures)
    generated: dict[Path, str] = {}

    for name in CONTRACTS:
        schema = contract_schema(name)
        generated[ROOT / "packages/contracts/schemas/v1" / f"{name}.schema.json"] = (
            json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
        )

    fixture_dir = ROOT / "packages/contracts/fixtures/v1"
    valid_output = [
        {"contract": name, "payload": payload}
        for name, payload in valid_fixtures.items()
    ]
    generated[fixture_dir / "valid.json"] = json.dumps(
        valid_output, indent=2, ensure_ascii=False
    ) + "\n"
    generated[fixture_dir / "invalid.json"] = json.dumps(
        invalid, indent=2, ensure_ascii=False
    ) + "\n"

    catalog_output = {}
    for name, (family, fields) in CONTRACTS.items():
        metadata = contract_metadata(name)
        metadata["fields"] = [
            {
                "name": field.name,
                "type": field.type_name,
                "required": field.required,
                "unit": unit_for(field.name, field.type_name),
                "reference_targets": (
                    split_targets(re.fullmatch(r"(?:ref|refs)<(.+)>", field.type_name)[1])
                    if re.fullmatch(r"(?:ref|refs)<(.+)>", field.type_name)
                    else (
                        sorted(SCHEMA_NAMES)
                        if field.type_name == "ref_list"
                        else []
                    )
                ),
            }
            for field in all_field_specs(name)
        ]
        catalog_output[name] = metadata
    generated[ROOT / "packages/contracts/catalog/v1/contracts.json"] = (
        json.dumps(catalog_output, indent=2, ensure_ascii=False) + "\n"
    )

    generated[ROOT / "packages/contracts/src/qc2_contracts/generated.py"] = (
        render_python_types()
    )
    generated[ROOT / "packages/contracts/src/qc2_contracts/generated.ts"] = (
        render_typescript(valid_fixtures)
    )
    generated[ROOT / "packages/contracts/android/Qc2WireContracts.kt"] = (
        render_kotlin_models()
    )
    generated[ROOT / "packages/contracts/android/Qc2WireFixtureSmoke.kt"] = (
        render_kotlin_fixtures(valid_fixtures)
    )
    generated[ROOT / "docs/reference/QC2-003_CONTRACT_CATALOG.md"] = (
        render_catalog_doc()
    )
    return generated


