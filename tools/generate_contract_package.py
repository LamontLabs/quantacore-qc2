def kotlin_literal(type_name: str, value: Any) -> str:
    if value is None:
        return "null"
    if type_name.startswith("nullable_"):
        return kotlin_literal(type_name.removeprefix("nullable_"), value)
    if type_name.startswith("enum<"):
        return json.dumps(value)
    if type_name.startswith("ref<"):
        return reference_literal(value)
    if type_name.startswith("refs<") or type_name == "ref_list":
        return "listOf(" + ", ".join(reference_literal(item) for item in value) + ")"
    if type_name in {"positive_int", "nonnegative_int"}:
        return f"{value}L"
    if type_name in {"boolean", "false_only"}:
        return "true" if value else "false"
    if type_name in {
        "text",
        "slug",
        "symbol",
        "currency_code",
        "base64url",
        "uuidv7",
        "utc_instant",
        "session",
        "timezone_id",
        "timezone",
        "sha256",
        "decimal",
        "continuous_decimal",
        "positive_decimal",
        "nonnegative_decimal",
        "probability",
        "fraction",
        "score",
        "decimal_fraction",
    }:
        return json.dumps(value, ensure_ascii=False)
    if type_name in {
        "text_list",
        "session_list",
        "decimal_list",
        "continuous_decimal_list",
        "hash_list",
    }:
        return "listOf(" + ", ".join(json.dumps(item) for item in value) + ")"
    if type_name == "feature_value_list":
        records = []
        for item in value:
            records.append(
                "FeatureValueRecord("
                f"feature_id = {json.dumps(item['feature_id'])}, "
                f"unit = {json.dumps(item['unit'])}, "
                f"value = {kotlin_literal('nullable_decimal', item.get('value'))}, "
                f"missing_reason = {kotlin_nullable_string(item.get('missing_reason'))}"
                ")"
            )
        return "listOf(" + ", ".join(records) + ")"
    if type_name == "gate_result_list":
        return "listOf(" + ", ".join(gate_result_literal(item) for item in value) + ")"
    if type_name == "artifact_file_list":
        return "listOf(" + ", ".join(artifact_file_literal(item) for item in value) + ")"
    if type_name == "evidence_value_list":
        return "listOf(" + ", ".join(evidence_value_literal(item) for item in value) + ")"
    if type_name == "outcome_field_validity_list":
        return "listOf(" + ", ".join(outcome_validity_literal(item) for item in value) + ")"
    if type_name == "test_count_list":
        return "listOf(" + ", ".join(test_count_literal(item) for item in value) + ")"
    raise ValueError(f"No Kotlin literal mapping for {type_name}")


def kotlin_nullable_string(value: Any) -> str:
    return "null" if value is None else json.dumps(value, ensure_ascii=False)


