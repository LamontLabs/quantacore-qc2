"""Render human-readable task documentation from the canonical task registry."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = ROOT / "registry/BUILD_TASKS.json"
BUILD_TASKS_PATH = ROOT / "docs/BUILD_TASKS.md"
DEPENDENCIES_PATH = ROOT / "docs/TASK_DEPENDENCIES.md"


def _list(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items) if items else "- None."


def _text(value: Any, default: str = "None.") -> str:
    return str(value) if value not in (None, "") else default


def _receipt_summary(task: dict[str, Any]) -> str:
    receipt = task.get("acceptance_receipt")
    if not receipt:
        return "Not recorded."
    paths = [
        receipt.get(key)
        for key in ("receipt", "contract_receipt", "task_record")
        if receipt.get(key)
    ]
    links = ", ".join(f"`{path}`" for path in paths)
    result = receipt.get("result", "unknown")
    checked = receipt.get("checked_at") or receipt.get("checked")
    suffix = f"; checked {checked}" if checked else ""
    summary = f"{result}{suffix}"
    return f"{summary}: {links}" if links else summary


def render_build_tasks(registry: dict[str, Any]) -> str:
    tasks = registry["tasks"]
    order = " → ".join(task["task_id"] for task in tasks)
    lines = [
        "<!-- Generated by tools/generate_task_docs.py; edit registry/BUILD_TASKS.json. -->",
        "# QuantraCore Apex Gen 2 — Canonical Build Tasks",
        "",
        f"**Canonical tasks:** QC2-000 through QC2-{len(tasks) - 1:03d} ({len(tasks)} total).",
        "**Initial project baseline:** NOT_STARTED, with every task initially TODO and no",
        "acceptance receipts at specification creation.",
        f"**Acceptance workflow version:** {registry.get('acceptance_workflow_version', 'unspecified')}.",
        "**Authority:** `docs/GEN2_MASTER_SPEC.md` and `registry/BUILD_TASKS.json`.",
        "**Execution rule:**",
        _text(registry.get("dependency_policy")),
        "**Task-board rule:** Native task-board status and merge labels are projections only; they never establish canonical PASS.",
        "**Current registry implementation status:**",
        _text(registry.get("implementation_status")),
        "",
        "## Common forbidden actions",
        "",
        _list(registry.get("common_forbidden_actions", [])),
        "",
        "## Exact topological order",
        "",
        f"`{order}`",
        "",
        "## Task contracts",
        "",
    ]

    common = set(registry.get("common_forbidden_actions", []))
    for task in tasks:
        dependencies = task.get("dependencies", [])
        legacy_refs = task.get("authorized_legacy_references", [])
        evidence = task.get("evidence_requirements", [])
        blockers = task.get("blockers", [])
        task_forbidden = [
            item for item in task.get("forbidden_actions", []) if item not in common
        ]
        lines.extend(
            [
                f"### {task['task_id']} — {task['name']}",
                "",
                f"**Current status:** {task['status']}",
                f"**Objective:** {task['objective']}",
                f"**Dependencies:** {', '.join(dependencies) if dependencies else 'None'}",
                "**Authorized legacy references:** "
                + (", ".join(legacy_refs) if legacy_refs else "None."),
            ]
        )
        if task.get("reference_mapping_rule"):
            lines.append(f"**Reference mapping rule:** {task['reference_mapping_rule']}")
        for authorization in task.get("authorized_artifact_drift", []):
            paths = ", ".join(
                f"`{path}`" for path in authorization.get("artifact_paths", [])
            )
            lines.append(
                "**Authorized artifact drift:** "
                f"{authorization.get('prior_task_id', 'unknown task')} — "
                f"{authorization.get('reason', 'No reason recorded')} "
                f"Paths: {paths or 'None.'}"
            )
        lines.extend(
            [
                f"**Required reference intake:** {task['required_reference_intake']}",
                "",
                "**Required deliverables:**",
                _list(task.get("required_deliverables", [])),
                "",
                "**Required tests:**",
                _list(task.get("required_tests", [])),
                "",
                "**Forbidden actions (task-specific and common):**",
                _list(task_forbidden + registry.get("common_forbidden_actions", [])),
                "",
                f"**Acceptance gate:** {task['acceptance_gate']}",
                "**Required evidence/environment:** "
                + (", ".join(evidence) if evidence else "None."),
                f"**Calibration dependency:** {task.get('calibration_dependency', 'Not stated.')}",
                f"**Blockers:** {', '.join(blockers) if blockers else 'None recorded.'}",
                f"**Acceptance receipt:** {_receipt_summary(task)}",
                "",
                "---",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def _contains_any(values: list[str], needles: tuple[str, ...]) -> bool:
    joined = " ".join(values).casefold()
    return any(needle.casefold() in joined for needle in needles)


def _task_ids(
    tasks: list[dict[str, Any]], predicate: Any
) -> list[str]:
    return [task["task_id"] for task in tasks if predicate(task)]


def _index_section(title: str, task_ids: list[str]) -> str:
    return f"### {title}\n\n{', '.join(task_ids) if task_ids else 'None'}\n"


def render_dependencies(registry: dict[str, Any]) -> str:
    tasks = registry["tasks"]
    rows = [
        "<!-- Generated by tools/generate_task_docs.py; edit registry/BUILD_TASKS.json. -->",
        "# Canonical dependency graph",
        "",
        "Exact topological execution order follows. Every noninitial task depends on",
        "its immediate predecessor; additional prerequisites make technical reuse explicit.",
        "",
        "| Task | Immediate predecessor | Additional technical prerequisites |",
        "| --- | --- | --- |",
    ]
    for index, task in enumerate(tasks):
        previous = tasks[index - 1]["task_id"] if index else None
        dependencies = task.get("dependencies", [])
        immediate = previous if previous in dependencies else None
        additional = [dep for dep in dependencies if dep != immediate]
        rows.append(
            "| "
            + " | ".join(
                [
                    task["task_id"],
                    immediate or "None",
                    ", ".join(additional) if additional else "None",
                ]
            )
            + " |"
        )

    def evidence_task(code: str) -> list[str]:
        return _task_ids(
            tasks, lambda task: code in task.get("evidence_requirements", [])
        )

    def legacy_task(needles: tuple[str, ...]) -> list[str]:
        return _task_ids(
            tasks,
            lambda task: _contains_any(
                task.get("authorized_legacy_references", []), needles
            ),
        )

    rows.extend(
        [
            "",
            "## Environment and dependency indexes",
            "",
            _index_section(
                "Tasks with authorized Gen 1 / QuantraCore references",
                legacy_task(("QuantraCore", "Gen 1", "Gen1", "ApexCore")),
            ),
            _index_section(
                "Tasks with authorized ApexLab references", legacy_task(("ApexLab",))
            ),
            _index_section(
                "Tasks with authorized original-protocol references",
                legacy_task(("original", "protocol concept")),
            ),
            _index_section("Tasks requiring real market data", evidence_task("REAL_MARKET_DATA")),
            _index_section("Tasks explicitly requiring Alpaca credentials", evidence_task("ALPACA_CREDENTIALS")),
            _index_section(
                "Tasks requiring Android/device work",
                _task_ids(
                    tasks,
                    lambda task: _contains_any(
                        task.get("evidence_requirements", []),
                        ("ANDROID", "REAL_ANDROID_DEVICE"),
                    ),
                ),
            ),
            _index_section(
                "Tasks requiring external access or owner authority",
                _task_ids(
                    tasks,
                    lambda task: _contains_any(
                        task.get("evidence_requirements", []),
                        (
                            "OWNER",
                            "INDEPENDENT",
                            "BACKUP_DESTINATION_ACCESS",
                            "IDENTITY_INTEGRATION",
                            "INTEGRATED_",
                            "PAPER_READ_ONLY_INTEGRATION",
                            "PRODUCTION_READINESS",
                            "REAL_BACKUP_ARTIFACTS",
                        ),
                    ),
                ),
            ),
            _index_section(
                "Tasks with calibration or real-evidence dependencies",
                _task_ids(
                    tasks,
                    lambda task: task.get("calibration_dependency")
                    == "CALIBRATION_REQUIRED",
                ),
            ),
            "Prerequisites are transitive: later tasks may rely on earlier capabilities",
            "through their dependency graph. Reference indexes describe authorization labels,",
            "not source access or inspection; evidence indexes describe explicit requirements.",
            "",
        ]
    )
    return "\n".join(rows).rstrip() + "\n"


def render_documents() -> dict[Path, str]:
    registry = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    return {
        BUILD_TASKS_PATH: render_build_tasks(registry),
        DEPENDENCIES_PATH: render_dependencies(registry),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail instead of writing when generated documents are stale",
    )
    args = parser.parse_args()
    stale: list[str] = []
    for path, content in render_documents().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("stale generated task documents: " + ", ".join(stale))
        return 1
    if args.check:
        print("task documentation matches registry")
    else:
        print("generated docs/BUILD_TASKS.md and docs/TASK_DEPENDENCIES.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
