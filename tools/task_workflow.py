class WorkflowError(ValueError):
    """Raised when task-state changes would violate the acceptance workflow."""


def _read_registry(root: Path = ROOT) -> dict[str, Any]:
    return json.loads((root / "registry/BUILD_TASKS.json").read_text(encoding="utf-8"))


def _write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(value, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def _git(root: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        check=check,
        capture_output=True,
        text=True,
        timeout=30,
    )


def _git_bytes(root: Path, *args: str) -> bytes:
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        check=True,
        capture_output=True,
        timeout=30,
    )
    return result.stdout


def _source_commit_available(root: Path, commit: str) -> bool:
    if not COMMIT_PATTERN.fullmatch(commit):
        return False
    exists = _git(root, "cat-file", "-e", f"{commit}^{{commit}}", check=False)
    if exists.returncode != 0:
        return False
    current = _git(root, "rev-parse", "HEAD").stdout.strip()
    return _git(
        root, "merge-base", "--is-ancestor", commit, current, check=False
    ).returncode == 0


def _safe_path(root: Path, value: str) -> Path:
    relative = Path(value)
    if relative.is_absolute() or ".." in relative.parts or not value.strip():
        raise WorkflowError(f"artifact path must be a safe workspace-relative path: {value}")
    path = (root / relative).resolve()
    if path != root and root not in path.parents:
        raise WorkflowError(f"artifact path escapes the workspace: {value}")
    if not path.exists():
        raise WorkflowError(f"acceptance artifact is missing: {value}")
    return path


def _artifact_hash(root: Path, value: str) -> str:
    path = _safe_path(root, value)
    if path.is_file():
        return hashlib.sha256(path.read_bytes()).hexdigest()
    if not path.is_dir():
        raise WorkflowError(f"artifact must be a file or directory: {value}")
    files: list[Path] = []
    for child in path.rglob("*"):
        if any(part in EXCLUDED_DIRS for part in child.relative_to(path).parts):
            continue
        if child.is_symlink():
            raise WorkflowError(f"symlink is not allowed in acceptance inventory: {child}")
        if child.is_file():
            files.append(child)
    if not files:
        raise WorkflowError(f"acceptance artifact directory is empty: {value}")
    digest = hashlib.sha256()
    for child in sorted(files, key=lambda item: item.relative_to(root).as_posix()):
        relative = child.relative_to(root).as_posix()
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(hashlib.sha256(child.read_bytes()).hexdigest().encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def _git_blob_records(
    root: Path, revision: str, value: str
) -> list[tuple[str, str, str, str]]:
    listing = _git(
        root, "ls-tree", "-r", "-z", "--full-tree", revision, "--", value
    ).stdout
    records: list[tuple[str, str, str, str]] = []
    for item in listing.split("\0"):
        if not item:
            continue
        metadata, relative = item.split("\t", 1)
        mode, object_type, object_id = metadata.split()
        records.append((mode, object_type, object_id, relative))
    return records


def _artifact_hash_at_commit(root: Path, commit: str, value: str) -> str:
    workspace_path = _safe_path(root, value)
    value = value.rstrip("/")
    records = _git_blob_records(root, commit, value)
    files: list[tuple[str, bytes]] = []
    for mode, object_type, object_id, relative in records:
        parts = Path(relative).parts
        if any(part in EXCLUDED_DIRS for part in parts):
            continue
        if object_type != "blob" or mode == "120000":
            raise WorkflowError(
                f"acceptance artifact is not a regular file at {commit}: {relative}"
            )
        if workspace_path.is_dir() and not relative.startswith(value + "/"):
            continue
        if not workspace_path.is_dir() and relative != value:
            continue
        files.append(
            (relative, _git_bytes(root, "cat-file", "blob", object_id))
        )

    if not workspace_path.is_dir():
        if len(files) != 1:
            raise WorkflowError(f"artifact is absent from tested commit: {value}")
        return hashlib.sha256(files[0][1]).hexdigest()
    if not files:
        raise WorkflowError(f"acceptance artifact directory is empty at {commit}: {value}")

    digest = hashlib.sha256()
    for relative, content in sorted(files, key=lambda item: item[0]):
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(hashlib.sha256(content).hexdigest().encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def _require_integrated_file(root: Path, value: str) -> None:
    workspace_path = _safe_path(root, value)
    if not workspace_path.is_file() or workspace_path.is_symlink():
        raise WorkflowError(f"acceptance record is not a regular file: {value}")
    records = [
        record
        for record in _git_blob_records(root, "HEAD", value)
        if record[3] == value
    ]
    if len(records) != 1:
        raise WorkflowError(f"acceptance record is not integrated in HEAD: {value}")
    mode, object_type, object_id, _ = records[0]
    if object_type != "blob" or mode == "120000":
        raise WorkflowError(f"acceptance record is not a regular Git blob: {value}")
    if _git_bytes(root, "cat-file", "blob", object_id) != workspace_path.read_bytes():
        raise WorkflowError(f"integrated acceptance record differs from workspace: {value}")


def _acceptance_checklist_errors(
    task: dict[str, Any], markdown: str
) -> list[str]:
    task_id = task["task_id"]
    marker = "## Acceptance checklist"
    if marker not in markdown:
        return [f"{task_id}: acceptance checklist is missing"]
    checklist = markdown.split(marker, 1)[1]
    next_heading = re.search(r"(?m)^## ", checklist)
    if next_heading:
        checklist = checklist[: next_heading.start()]

    expected = {
        ("DELIVERABLE", item) for item in task.get("required_deliverables", [])
    } | {("TEST", item) for item in task.get("required_tests", [])}
    found: set[tuple[str, str]] = set()
    errors: list[str] = []
    for line in checklist.splitlines():
        if not line.startswith("- [x] "):
            continue
        item = line[len("- [x] ") :]
        kind = next(
            (candidate for candidate in ("DELIVERABLE", "TEST") if item.startswith(f"{candidate}: ")),
            None,
        )
        if kind is None:
            errors.append(f"{task_id}: acceptance checklist has an unknown entry")
            continue
        body = item[len(kind) + 2 :]
        description, separator, evidence = body.partition(" | evidence: ")
        key = (kind, description)
        if not separator or not evidence.strip():
            errors.append(f"{task_id}: checklist entry lacks evidence: {description}")
        if key not in expected:
            errors.append(f"{task_id}: checklist entry is not in the task contract: {description}")
        if key in found:
            errors.append(f"{task_id}: duplicate acceptance checklist entry: {description}")
        found.add(key)

    for kind, description in sorted(expected - found):
        errors.append(f"{task_id}: required {kind.lower()} is not checked: {description}")
    return errors


def _receipt_paths(receipt: dict[str, Any]) -> list[str]:
    return [
        receipt[key]
        for key in ("receipt", "contract_receipt", "task_record")
        if isinstance(receipt.get(key), str)
    ]


def _authorized_artifact_drift(
    registry: dict[str, Any],
    prior_task_id: str,
    artifact_path: str,
    current_hash: str,
) -> str | None:
    """Return a reason only when a later task explicitly accepts this exact artifact change."""
    tasks = registry.get("tasks", [])
    positions = {
        task.get("task_id"): index
        for index, task in enumerate(tasks)
        if isinstance(task, dict)
    }
    prior_position = positions.get(prior_task_id)
    if prior_position is None:
        return None

    for later in tasks[prior_position + 1 :]:
        for authorization in later.get("authorized_artifact_drift", []):
            if (
                authorization.get("prior_task_id") != prior_task_id
                or artifact_path not in authorization.get("artifact_paths", [])
            ):
                continue
            reason = authorization.get("reason")
            if later.get("status") == "TODO" and authorization.get(
                "approved_before_start"
            ) is True:
                return reason if isinstance(reason, str) and reason.strip() else None
            if later.get("status") == "IN_PROGRESS":
                return reason if isinstance(reason, str) and reason.strip() else None
            if later.get("status") != "PASS":
                continue
            receipt = later.get("acceptance_receipt")
            if not isinstance(receipt, dict) or receipt.get("result") != "PASS":
                continue
            if artifact_path not in receipt.get("changed_paths", []):
                continue
            if receipt.get("artifact_hashes", {}).get(artifact_path) != current_hash:
                continue
            if isinstance(reason, str) and reason.strip():
                return reason
    return None


def _validate_contract_receipt(
    root: Path,
    registry: dict[str, Any],
    task: dict[str, Any],
    receipt: dict[str, Any],
    require_integrated: bool = False,
) -> list[str]:
    errors: list[str] = []
    task_id = task["task_id"]
    required = (
        "checked_at",
        "task_spec_version",
        "source_commit",
        "receipt",
        "contract_receipt",
        "task_record",
        "executed_commands",
        "test_counts",
        "artifact_hashes",
    )
    for key in required:
        if key not in receipt:
            errors.append(f"{task_id}: acceptance receipt metadata lacks {key}")
    if errors:
        return errors
    if receipt.get("result") != "PASS":
        errors.append(f"{task_id}: registry result is not PASS")
    workflow_version = receipt.get("acceptance_workflow_version")
    if workflow_version not in (None, WORKFLOW_VERSION):
        errors.append(f"{task_id}: unsupported acceptance workflow version {workflow_version}")
    if not _source_commit_available(root, receipt["source_commit"]):
        errors.append(f"{task_id}: tested source commit is unavailable or not integrated")
    if not receipt["executed_commands"] or not receipt["test_counts"]:
        errors.append(f"{task_id}: commands and test counts are required")
    if not isinstance(receipt["artifact_hashes"], dict) or not receipt["artifact_hashes"]:
        errors.append(f"{task_id}: artifact path/hash inventory is required")
    for artifact_path, expected_hash in receipt["artifact_hashes"].items():
        try:
            actual_hash = _artifact_hash(root, artifact_path)
            tested_hash = _artifact_hash_at_commit(
                root, receipt["source_commit"], artifact_path
            )
        except WorkflowError as exc:
            errors.append(f"{task_id}: {exc}")
            continue
        if actual_hash != expected_hash and _authorized_artifact_drift(
            registry, task_id, artifact_path, actual_hash
        ) is None:
            errors.append(
                f"{task_id}: artifact hash changed without an authorized downstream acceptance: {artifact_path}"
            )
        if tested_hash != expected_hash:
            errors.append(
                f"{task_id}: artifact does not match tested source commit: {artifact_path}"
            )
        if require_integrated:
            try:
                integrated_hash = _artifact_hash_at_commit(root, "HEAD", artifact_path)
            except WorkflowError as exc:
                errors.append(f"{task_id}: {exc}")
                continue
            if integrated_hash != expected_hash and _authorized_artifact_drift(
                registry, task_id, artifact_path, integrated_hash
            ) is None:
                errors.append(
                    f"{task_id}: artifact does not match integrated HEAD or authorized downstream acceptance: {artifact_path}"
                )

    for key in ("receipt", "contract_receipt", "task_record"):
        try:
            _safe_path(root, receipt[key])
            if require_integrated:
                _require_integrated_file(root, receipt[key])
        except WorkflowError as exc:
            errors.append(f"{task_id}: {exc}")
    if errors:
        return errors

    try:
        markdown = (root / receipt["receipt"]).read_text(encoding="utf-8")
        if METADATA_MARKER not in markdown:
            errors.append(f"{task_id}: Markdown receipt has no generated acceptance metadata")
        if receipt["checked_at"] not in markdown:
            errors.append(f"{task_id}: Markdown receipt does not identify the checked time")
        if receipt["source_commit"] not in markdown:
            errors.append(f"{task_id}: Markdown receipt does not identify the tested commit")
        if workflow_version == WORKFLOW_VERSION:
            if WORKFLOW_VERSION not in markdown:
                errors.append(f"{task_id}: Markdown receipt omits its acceptance workflow version")
            errors.extend(_acceptance_checklist_errors(task, markdown))

        task_record = json.loads(
            (root / receipt["task_record"]).read_text(encoding="utf-8")
        )
        validate_contract("BuildTask", task_record)
        verify_content_hash("BuildTask", task_record)
        if task_record["task_id"] != task_id.lower():
            errors.append(f"{task_id}: structured task record identifies another task")
        if task_record["task_state"] != "PASS":
            errors.append(f"{task_id}: structured task record is not PASS")

        acceptance_record = json.loads(
            (root / receipt["contract_receipt"]).read_text(encoding="utf-8")
        )
        validate_contract("TaskAcceptanceReceipt", acceptance_record)
        verify_content_hash("TaskAcceptanceReceipt", acceptance_record)
        if acceptance_record["gate_verdict"] != "PASS":
            errors.append(f"{task_id}: structured acceptance receipt is not PASS")
        if acceptance_record["source_commit"] != receipt["source_commit"]:
            errors.append(f"{task_id}: source commit differs between receipt records")
        if acceptance_record["checked_at"] != receipt["checked_at"]:
            errors.append(f"{task_id}: checked time differs between receipt records")
        if acceptance_record["task_spec_version"] != receipt["task_spec_version"]:
            errors.append(f"{task_id}: task specification version differs between receipt records")
        if acceptance_record["task_ref"]["target_id"] != task_record["id"]:
            errors.append(f"{task_id}: acceptance receipt points to another task record")
        if acceptance_record["task_ref"]["content_hash"] != task_record["content_hash"]:
            errors.append(f"{task_id}: acceptance receipt task reference hash is stale")
        if acceptance_record["changed_paths"] != list(receipt["artifact_hashes"]):
            errors.append(f"{task_id}: artifact paths differ between receipt records")
        if acceptance_record["artifact_hashes"] != list(
            receipt["artifact_hashes"].values()
        ):
            errors.append(f"{task_id}: artifact hashes differ between receipt records")
        if acceptance_record["executed_commands"] != receipt["executed_commands"]:
            errors.append(f"{task_id}: commands differ between receipt records")
        if acceptance_record["test_counts"] != receipt["test_counts"]:
            errors.append(f"{task_id}: test counts differ between receipt records")
    except (OSError, json.JSONDecodeError, KeyError, WorkflowError, ValueError) as exc:
        errors.append(f"{task_id}: invalid structured acceptance evidence: {exc}")
    return errors


def validate_registry(
    registry: dict[str, Any],
    root: Path = ROOT,
    check_documents: bool = False,
    require_integrated: bool = False,
) -> list[str]:
    errors: list[str] = []
    if registry.get("acceptance_workflow_version") != WORKFLOW_VERSION:
        errors.append(
            f"registry acceptance workflow version must be {WORKFLOW_VERSION}"
        )
    tasks = registry.get("tasks")
    if not isinstance(tasks, list) or len(tasks) != registry.get("task_count"):
        return ["registry task_count does not match its task list"]
    by_id = {task.get("task_id"): task for task in tasks}
    if len(by_id) != len(tasks):
        errors.append("registry task IDs are not unique")
    if [task.get("task_id") for task in tasks] != [
        f"QC2-{index:03d}" for index in range(len(tasks))
    ]:
        errors.append("registry tasks are not in canonical QC2 sequence")

    in_progress = [task for task in tasks if task.get("status") == "IN_PROGRESS"]
    if len(in_progress) > 1:
        errors.append("more than one canonical task is IN_PROGRESS")

    for index, task in enumerate(tasks):
        task_id = task.get("task_id", "<missing task ID>")
        status = task.get("status")
        if status not in VALID_STATUSES:
            errors.append(f"{task_id}: unknown status {status!r}")
        dependencies = task.get("dependencies", [])
        for dependency_id in dependencies:
            if dependency_id not in by_id:
                errors.append(f"{task_id}: unknown dependency {dependency_id}")
        if status == "PASS":
            receipt = task.get("acceptance_receipt")
            if not isinstance(receipt, dict) or receipt.get("result") != "PASS":
                errors.append(f"{task_id}: PASS requires a PASS acceptance receipt")
            elif index >= 3:
                errors.extend(
                    _validate_contract_receipt(
                        root,
                        registry,
                        task,
                        receipt,
                        require_integrated=require_integrated,
                    )
                )
            else:
                for path in _receipt_paths(receipt):
                    try:
                        _safe_path(root, path)
                        if require_integrated:
                            _require_integrated_file(root, path)
                    except WorkflowError as exc:
                        errors.append(f"{task_id}: {exc}")
        elif status == "TODO" and task.get("acceptance_receipt") is not None:
            errors.append(f"{task_id}: TODO task has an acceptance receipt")

    if not topological_task_order(tasks):
        errors.append("dependency graph contains a cycle")

    if in_progress:
        active = in_progress[0]
        for dependency_id in active.get("dependencies", []):
            dependency = by_id.get(dependency_id)
            if dependency and dependency.get("status") != "PASS":
                errors.append(
                    f"{active['task_id']}: dependency {dependency_id} is not PASS"
                )
            elif dependency:
                receipt = dependency.get("acceptance_receipt")
                if not isinstance(receipt, dict) or receipt.get("result") != "PASS":
                    errors.append(
                        f"{active['task_id']}: dependency {dependency_id} lacks acceptance evidence"
                    )

    if check_documents:
        expected_documents = {
            "docs/BUILD_TASKS.md": render_build_tasks(registry),
            "docs/TASK_DEPENDENCIES.md": render_dependencies(registry),
        }
        for relative, expected in expected_documents.items():
            path = root / relative
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                errors.append(
                    f"generated task document is stale: {relative}"
                )
    if require_integrated and not in_progress:
        for relative in (
            "registry/BUILD_TASKS.json",
            "docs/BUILD_TASKS.md",
            "docs/TASK_DEPENDENCIES.md",
        ):
            try:
                _require_integrated_file(root, relative)
            except WorkflowError as exc:
                errors.append(str(exc))
    return errors


def _task_map(registry: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {task["task_id"]: task for task in registry["tasks"]}


def _preflight_errors(
    registry: dict[str, Any], task_id: str, root: Path = ROOT
) -> list[str]:
    tasks = _task_map(registry)
    task = tasks.get(task_id)
    if task is None:
        return [f"unknown task: {task_id}"]
    errors: list[str] = []
    if task.get("status") == "TODO":
        for relative in (
            "registry/BUILD_TASKS.json",
            "docs/BUILD_TASKS.md",
            "docs/TASK_DEPENDENCIES.md",
        ):
            try:
                _require_integrated_file(root, relative)
            except WorkflowError as exc:
                errors.append(str(exc))
    for dependency_id in task.get("dependencies", []):
        dependency = tasks[dependency_id]
        if dependency.get("status") != "PASS":
            errors.append(f"{dependency_id} is not PASS")
            continue
        receipt = dependency.get("acceptance_receipt")
        if not isinstance(receipt, dict) or receipt.get("result") != "PASS":
            errors.append(f"{dependency_id} has no PASS acceptance receipt")
        elif dependency_id >= "QC2-003":
            errors.extend(
                _validate_contract_receipt(
                    root,
                    registry,
                    dependency,
                    receipt,
                    require_integrated=True,
                )
            )
        else:
            for path in _receipt_paths(receipt):
                try:
                    _safe_path(root, path)
                    _require_integrated_file(root, path)
                except WorkflowError as exc:
                    errors.append(f"{dependency_id}: {exc}")
    return errors


def _update_local_task(
    root: Path, task_id: str, status: str, acceptance_receipt: dict[str, Any] | None = None
) -> None:
    path = root / ".local/tasks" / f"{task_id}.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")

    def replace_section(source: str, heading: str, body: str) -> str:
        start = source.find(heading)
        if start < 0:
            return source.rstrip() + "\n\n" + heading + "\n\n" + body + "\n"
        content_start = start + len(heading)
        end = source.find("\n## ", content_start)
        if end < 0:
            end = len(source)
        return source[:start] + heading + "\n\n" + body + "\n" + source[end:]

    state_body = f"- **Current registry status:** {status}"
    if acceptance_receipt:
        state_body += (
            f"\n- **Acceptance receipt:** `{acceptance_receipt['receipt']}`"
            f"\n- **Structured receipt:** `{acceptance_receipt['contract_receipt']}`"
            f"\n- **Task record:** `{acceptance_receipt['task_record']}`"
        )
    text = replace_section(text, "## Current registry state", state_body)
    if acceptance_receipt:
        text = replace_section(
            text,
            "## Acceptance receipt",
            "\n".join(
                [
                    "- **Result:** PASS",
                    f"- **Checked at (UTC):** {acceptance_receipt['checked_at']}",
                    f"- **Assessment:** `{acceptance_receipt['receipt']}`",
                    f"- **Structured receipt:** `{acceptance_receipt['contract_receipt']}`",
                    f"- **Task record:** `{acceptance_receipt['task_record']}`",
                ]
            ),
        )
    path.write_text(text, encoding="utf-8", newline="\n")


def _render_all_documents(registry: dict[str, Any], root: Path) -> None:
    documents = {
        "docs/BUILD_TASKS.md": render_build_tasks(registry),
        "docs/TASK_DEPENDENCIES.md": render_dependencies(registry),
    }
    for relative, content in documents.items():
        destination = root / relative
        destination.write_text(content, encoding="utf-8", newline="\n")


def start_task(task_id: str, root: Path = ROOT) -> None:
    registry = _read_registry(root)
    tasks = _task_map(registry)
    task = tasks.get(task_id)
    if task is None:
        raise WorkflowError(f"unknown task: {task_id}")
    if task.get("status") != "TODO":
        raise WorkflowError(f"{task_id} must be TODO before it can start")
    if any(item.get("status") == "IN_PROGRESS" for item in registry["tasks"]):
        raise WorkflowError("another canonical task is already IN_PROGRESS")
    errors = _preflight_errors(registry, task_id, root)
    if errors:
        raise WorkflowError("preflight failed: " + "; ".join(errors))
    task["status"] = "IN_PROGRESS"
    _write_json(root / "registry/BUILD_TASKS.json", registry)
    _render_all_documents(registry, root)
    _update_local_task(root, task_id, "IN_PROGRESS")


def _parse_test_count(value: str) -> dict[str, int | str]:
    parts = value.split(":")
    if len(parts) != 4 or not TEST_ID_PATTERN.fullmatch(parts[0]):
        raise WorkflowError(
            "test count must be test_id:passed:failed:skipped using a lowercase ID"
        )
    try:
        passed, failed, skipped = (int(part) for part in parts[1:])
    except ValueError as exc:
        raise WorkflowError("test counts must be nonnegative integers") from exc
    if min(passed, failed, skipped) < 0:
        raise WorkflowError("test counts must be nonnegative integers")
    return {
        "test_id": parts[0],
        "passed": passed,
        "failed": failed,
        "skipped": skipped,
    }


def _evidence_requirement_slug(task: dict[str, Any]) -> str:
    requirements = task.get("evidence_requirements") or [
        "local_fixture_and_code_evidence"
    ]
    if not isinstance(requirements, list):
        raise WorkflowError("evidence_requirements must be a list")

    normalized: list[str] = []
    for requirement in requirements:
        if not isinstance(requirement, str) or not requirement.strip():
            raise WorkflowError("evidence requirements must be non-empty strings")
        token = re.sub(r"[^a-z0-9_-]+", "_", requirement.strip().lower()).strip("_-")
        if not token:
            raise WorkflowError("evidence requirements must produce lowercase identifiers")
        normalized.append(token)

    # BuildTask v1 has one evidence_requirement field; retain every registry
    # requirement as a conjunctive identifier in that field.
    slug = "_and_".join(normalized)
    if not re.fullmatch(r"[a-z][a-z0-9_-]{0,95}", slug):
        raise WorkflowError("combined evidence requirement exceeds BuildTask v1 limits")
    return slug


def _utc_now() -> str:
    return (
        datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def finish_task(args: argparse.Namespace, root: Path = ROOT) -> None:
    registry = _read_registry(root)
    tasks = _task_map(registry)
    task = tasks.get(args.task_id)
    if task is None:
        raise WorkflowError(f"unknown task: {args.task_id}")
    if task.get("status") != "IN_PROGRESS":
        raise WorkflowError(f"{args.task_id} must be IN_PROGRESS before acceptance")
    errors = _preflight_errors(registry, args.task_id, root)
    if errors:
        raise WorkflowError("preflight failed: " + "; ".join(errors))
    if not args.commands:
        raise WorkflowError("at least one executed acceptance command is required")
    counts = [_parse_test_count(item) for item in args.test_count]
    if not counts:
        raise WorkflowError("at least one test count is required")
    if not any(
        count["passed"] + count["failed"] + count["skipped"] > 0 for count in counts
    ):
        raise WorkflowError("at least one executed acceptance test must be counted")
    if any(count["failed"] for count in counts):
        raise WorkflowError("a task with failed acceptance tests cannot be marked PASS")
    skipped = sum(int(count["skipped"]) for count in counts)
    if skipped and not args.skip_reason:
        raise WorkflowError("skipped acceptance tests require --skip-reason")
    if not args.artifact_path:
        raise WorkflowError("at least one implementation artifact path is required")
    if not _source_commit_available(root, args.source_commit):
        raise WorkflowError("source commit must exist and be integrated into current HEAD")
    evidence_path = _safe_path(root, args.evidence)
    if not evidence_path.is_file() or "## Acceptance assessment" not in evidence_path.read_text(
        encoding="utf-8"
    ):
        raise WorkflowError("assessment must be a Markdown file with an Acceptance assessment")
    report = evidence_path.read_text(encoding="utf-8")
    if METADATA_MARKER in report:
        raise WorkflowError("assessment already has generated completion metadata")
    if not re.search(r"(?im)^\s*[-*]\s*\*\*Result:\*\*\s*PASS", report):
        raise WorkflowError("assessment must explicitly state **Result:** PASS")
    checklist_errors = _acceptance_checklist_errors(task, report)
    if checklist_errors:
        raise WorkflowError("acceptance checklist failed: " + "; ".join(checklist_errors))

    artifact_hashes = {
        item.rstrip("/"): _artifact_hash(root, item.rstrip("/"))
        for item in args.artifact_path
    }
    if len(artifact_hashes) != len(args.artifact_path):
        raise WorkflowError("artifact paths must be unique")
    for artifact_path, expected_hash in artifact_hashes.items():
        tested_hash = _artifact_hash_at_commit(
            root, args.source_commit, artifact_path
        )
        if tested_hash != expected_hash:
            raise WorkflowError(
                f"artifact does not match tested source commit: {artifact_path}"
            )
    checked_at = _utc_now()
    task_record = {
        "schema_name": "qc2.integrity_build.BuildTask.v1",
        "schema_version": "1.0",
        "id": new_uuidv7(),
        "created_at": checked_at,
        "owning_authority": "build_governance",
        "evidence_class": args.evidence_class,
        "environment_namespace": args.environment,
        "source_refs": [],
        "content_hash": "0" * 64,
        "task_id": task["task_id"].lower(),
        "task_name": task["name"],
        "objective": task["objective"],
        "dependency_task_ids": task.get("dependencies", []),
        "authorized_legacy_refs": task.get("authorized_legacy_references", []),
        "deliverable_refs": task.get("required_deliverables", []),
        "required_test_refs": task.get("required_tests", []),
        "acceptance_gate": task["acceptance_gate"],
        "evidence_requirement": _evidence_requirement_slug(task),
        "calibration_dependency": task.get(
            "calibration_dependency", "FRAMEWORK_OR_POLICY_ONLY"
        ),
        "task_state": "PASS",
        "blocker_refs": task.get("blockers", []),
    }
    task_record["content_hash"] = canonical_content_hash("BuildTask", task_record)
    validate_contract("BuildTask", task_record)
    verify_content_hash("BuildTask", task_record)

    receipt_base = f"docs/reference/{task_id_file(args.task_id)}"
    task_record_path = f"{receipt_base}_TASK_RECORD.json"
    contract_receipt_path = f"{receipt_base}_ACCEPTANCE_RECORD.json"
    markdown_path = args.evidence
    task_ref = {
        "target_schema_name": "qc2.integrity_build.BuildTask.v1",
        "target_id": task_record["id"],
        "content_hash": task_record["content_hash"],
    }
    acceptance_record = {
        "schema_name": "qc2.integrity_build.TaskAcceptanceReceipt.v1",
        "schema_version": "1.0",
        "id": new_uuidv7(),
        "created_at": checked_at,
        "owning_authority": "build_governance",
        "evidence_class": args.evidence_class,
        "environment_namespace": args.environment,
        "source_refs": [],
        "content_hash": "0" * 64,
        "task_ref": task_ref,
        "task_spec_version": (
            f"{args.task_id} / registry schema {registry['schema_version']} / "
            f"governing spec {registry['spec_version']} / "
            f"acceptance workflow {WORKFLOW_VERSION}"
        ),
        "source_commit": args.source_commit,
        "changed_paths": list(artifact_hashes),
        "executed_commands": args.commands,
        "test_counts": counts,
        "artifact_hashes": list(artifact_hashes.values()),
        "legacy_intake_refs": [],
        "unresolved_decisions": [],
        "gate_verdict": "PASS",
        "agent_identity": "Replit Agent",
        "reviewer_identity": None,
        "checked_at": checked_at,
    }
    acceptance_record["content_hash"] = canonical_content_hash(
        "TaskAcceptanceReceipt", acceptance_record
    )
    validate_contract("TaskAcceptanceReceipt", acceptance_record)
    verify_content_hash("TaskAcceptanceReceipt", acceptance_record)

    receipt_meta = {
        "result": "PASS",
        "acceptance_workflow_version": WORKFLOW_VERSION,
        "checked_at": checked_at,
        "task_spec_version": acceptance_record["task_spec_version"],
        "source_commit": args.source_commit,
        "receipt": markdown_path,
        "contract_receipt": contract_receipt_path,
        "task_record": task_record_path,
        "changed_paths": list(artifact_hashes),
        "executed_commands": args.commands,
        "test_counts": counts,
        "artifact_hashes": artifact_hashes,
        "evidence_class": args.evidence_class,
        "environment_namespace": args.environment,
        "verification_reason": (
            args.verification_reason
            or "Acceptance was performed now because trustworthy historical evidence was missing."
        ),
        "agent_identity": "Replit Agent",
        "reviewer_identity": None,
    }
    metadata_lines = [
        METADATA_MARKER,
        "",
        "- **Result:** PASS",
        f"- **Checked at (UTC):** {checked_at}",
        f"- **Acceptance workflow version:** {WORKFLOW_VERSION}",
        f"- **Task/specification version:** {receipt_meta['task_spec_version']}",
        f"- **Tested source commit:** `{args.source_commit}`",
        f"- **Verification reason:** {receipt_meta['verification_reason']}",
        f"- **Evidence:** `{markdown_path}`; `{contract_receipt_path}`; `{task_record_path}`",
        f"- **Evidence class/environment:** `{args.evidence_class}` / `{args.environment}`",
        "- **Commands executed:**",
    ]
    metadata_lines.extend(f"  - `{command}`" for command in args.commands)
    metadata_lines.append("- **Test counts:**")
    metadata_lines.extend(
        "  - `{test_id}`: {passed} passed, {failed} failed, {skipped} skipped".format(
            **count
        )
        for count in counts
    )
    if args.skip_reason:
        metadata_lines.append(f"- **Skip rationale:** {args.skip_reason}")
    metadata_lines.append("- **Artifact hashes:**")
    metadata_lines.extend(
        f"  - `{path}` — `{digest}`" for path, digest in artifact_hashes.items()
    )
    metadata_lines.extend(
        [
            "- **Independent reviewer:** None supplied; this is a self-assessment.",
            "",
        ]
    )

    _write_json(root / task_record_path, task_record)
    _write_json(root / contract_receipt_path, acceptance_record)
    evidence_path.write_text(
        report.rstrip() + "\n\n" + "\n".join(metadata_lines),
        encoding="utf-8",
        newline="\n",
    )
    task["status"] = "PASS"
    task["blockers"] = []
    task["acceptance_receipt"] = receipt_meta
    _write_json(root / "registry/BUILD_TASKS.json", registry)
    _render_all_documents(registry, root)
    _update_local_task(root, args.task_id, "PASS", receipt_meta)

    final_errors = validate_registry(registry, root, check_documents=True)
    if final_errors:
        raise WorkflowError("acceptance record validation failed: " + "; ".join(final_errors))


def task_id_file(task_id: str) -> str:
    if not re.fullmatch(r"QC2-[0-9]{3}", task_id):
        raise WorkflowError(f"invalid canonical task ID: {task_id}")
    return task_id


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="action", required=True)

    preflight = subparsers.add_parser("preflight", help="verify dependencies and receipts")
    preflight.add_argument("task_id")

    start = subparsers.add_parser("start", help="mark one eligible task IN_PROGRESS")
    start.add_argument("task_id")

    finish = subparsers.add_parser("finish", help="record acceptance and update the registry")
    finish.add_argument("task_id")
    finish.add_argument("--source-commit", required=True)
    finish.add_argument("--evidence", required=True)
    finish.add_argument("--artifact-path", action="append", default=[])
    finish.add_argument("--command", dest="commands", action="append", default=[])
    finish.add_argument("--test-count", action="append", default=[])
    finish.add_argument(
        "--evidence-class",
        choices=("SYNTHETIC_FIXTURE", "HISTORICAL_RECONSTRUCTED", "FORWARD_OPERATIONAL", "FORWARD_SEALED"),
        required=True,
    )
    finish.add_argument(
        "--environment",
        choices=("development", "test", "research", "production"),
        required=True,
    )
    finish.add_argument("--skip-reason")
    finish.add_argument("--verification-reason")

    subparsers.add_parser("validate", help="validate registry, receipts, and generated docs")
    args = parser.parse_args()
    try:
        if args.action == "preflight":
            registry = _read_registry()
            errors = _preflight_errors(registry, args.task_id)
            if errors:
                raise WorkflowError("preflight failed: " + "; ".join(errors))
            print(f"{args.task_id} dependencies and acceptance evidence are available")
        elif args.action == "start":
            start_task(args.task_id)
            print(f"{args.task_id} set to IN_PROGRESS; task docs regenerated")
        elif args.action == "finish":
            finish_task(args)
            print(f"{args.task_id} PASS recorded; receipts, registry, and task docs validated")
        else:
            errors = validate_registry(
                _read_registry(), check_documents=True, require_integrated=True
            )
            if errors:
                raise WorkflowError("; ".join(errors))
            print("task registry, acceptance records, and generated docs are valid")
    except (WorkflowError, OSError, json.JSONDecodeError, subprocess.SubprocessError) as exc:
        print(f"task workflow error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
